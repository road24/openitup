TABLE_SIZE = 1024


def _reverse_bits(byte: int) -> int:
    result = 0
    for i in range(8):
        result |= ((byte >> i) & 1) << (7 - i)
    return result


def _adler32(data: bytes) -> int:
    s1 = 1
    s2 = 0
    for b in data:
        s1 = (s1 + b) % 65521
        s2 = (s2 + s1) % 65521
    return (s2 << 16) + s1


def decode_enc2(data: bytes) -> bytes:
    """Decode an ENC2 encrypted file (PNZ or AUD).

    Returns the decrypted payload (PNG or MP3 data).
    Raises ValueError on invalid magic or checksum mismatch.
    """
    if len(data) < 140:
        raise ValueError("File too small for ENC2 header")

    magic = data[0:4]
    if magic != b"ENC2":
        raise ValueError(f"Invalid magic: {magic!r}, expected b'ENC2'")

    payload_size = struct.unpack_from("<I", data, 132)[0]
    dummy_size = struct.unpack_from("<I", data, 136)[0]

    pos = 140 + dummy_size
    if pos + 4 + TABLE_SIZE > len(data):
        raise ValueError("File truncated before cipher table")

    checksum = struct.unpack_from("<I", data, pos)[0]
    pos += 4

    cipher_table = bytearray(data[pos:pos + TABLE_SIZE])
    pos += TABLE_SIZE

    # Transform cipher table through lockchip in 16-byte chunks
    final_table = bytearray(TABLE_SIZE)
    for i in range(0, TABLE_SIZE, 16):
        chunk = lockchip_transform(bytes(cipher_table[i:i + 16]))
        final_table[i:i + 16] = chunk

    encrypted = data[pos:pos + payload_size]
    if len(encrypted) < payload_size:
        raise ValueError(f"Payload truncated: expected {payload_size}, got {len(encrypted)}")

    # Decrypt: reverse bits then XOR with transformed table
    decrypted = bytearray(payload_size)
    for i in range(payload_size):
        b = _reverse_bits(encrypted[i])
        b ^= final_table[i % TABLE_SIZE]
        decrypted[i] = b

    # Verify checksum
    computed = _adler32(decrypted)
    if computed != checksum:
        raise ValueError(f"Checksum mismatch: expected 0x{checksum:08X}, got 0x{computed:08X}")

    return bytes(decrypted)


def decode_pnz(filepath: str) -> bytes:
    """Decode a .PNZ file to PNG data."""
    with open(filepath, "rb") as f:
        return decode_enc2(f.read())


def decode_aud(filepath: str) -> bytes:
    """Decode a .AUD file to MP3 data."""
    with open(filepath, "rb") as f:
        return decode_enc2(f.read())
